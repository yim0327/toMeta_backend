
    create table anonymous_sessions (
        anonymous_session_id bigint generated by default as identity,
        created_at timestamp(6) not null,
        expires_at timestamp(6) not null,
        last_accessed_at timestamp(6),
        user_id bigint not null,
        token_hash varchar(64) not null,
        primary key (anonymous_session_id),
        constraint uk_anonymous_sessions_token_hash unique (token_hash)
    );

    create table cosmetic_ingredients (
        ingredient_order integer not null,
        is_main boolean not null,
        cosmetic_ingredient_id bigint generated by default as identity,
        cosmetic_product_id bigint not null,
        ingredient_id bigint,
        ingredient_name varchar(100) not null,
        primary key (cosmetic_ingredient_id),
        constraint uk_cosmetic_ingredients_product_order unique (cosmetic_product_id, ingredient_order)
    );

    create table cosmetic_products (
        cosmetic_product_id bigint generated by default as identity,
        created_at timestamp(6) not null,
        created_by_user_id bigint,
        updated_at timestamp(6) not null,
        source_type varchar(20) not null,
        product_type varchar(50) not null,
        brand_name varchar(100),
        product_name varchar(255) not null,
        source_key varchar(255),
        image_url clob,
        primary key (cosmetic_product_id)
    );

    create table cosmetic_set_items (
        item_order integer not null,
