        constraint uk_cosmetic_set_items_set_cosmetic unique (cosmetic_set_id, user_cosmetic_id),
        constraint uk_cosmetic_set_items_set_order unique (cosmetic_set_id, item_order)
    );

    create table cosmetic_sets (
        cosmetic_set_id bigint generated by default as identity,
        created_at timestamp(6) not null,
        updated_at timestamp(6) not null,
        user_id bigint not null,
        name varchar(100) not null,
        usage_time enum ('BOTH','MORNING','NIGHT') not null,
        primary key (cosmetic_set_id)
    );

